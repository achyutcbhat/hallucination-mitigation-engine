from config.settings import settings
from config.logging_config import setup_logger
from src.schemas.input import ProcessedInput
from src.schemas.agent import AgentCandidateResponse, CandidatePool
from src.stage_03_multiagent_engine.agent_pool import AgentRunner

logger = setup_logger("Stage03-Generator")

# Varied temperatures for Dual-Candidate diversity:
# Iteration 1 = 0.7 (Focused), Iteration 2 = 0.85 (Exploratory)
TEMPERATURE_PROFILES = [0.7, 0.85]


def run_multiagent_generation(processed_input: ProcessedInput) -> CandidatePool:
    logger.info("=" * 60)
    logger.info(
        "Starting Multi-Agent Engine: 3 Agents x 2 Runs = 6 Candidate Pool"
    )
    logger.info("=" * 60)

    sub_q_texts = [q.sub_question for q in processed_input.sub_questions]
    candidates: list[AgentCandidateResponse] = []
    candidate_id_counter = 1

    for model_name in settings.AGENT_MODELS:
        agent = AgentRunner(model_name=model_name)

        for iteration_idx in range(settings.CANDIDATES_PER_AGENT):
            temp = TEMPERATURE_PROFILES[iteration_idx % len(TEMPERATURE_PROFILES)]
            iteration_number = iteration_idx + 1

            response_text, latency = agent.generate_candidate(
                query=processed_input.raw_query,
                sub_questions=sub_q_texts,
                iteration=iteration_number,
                temperature=temp,
            )

            candidate = AgentCandidateResponse(
                candidate_id=candidate_id_counter,
                agent_model=model_name,
                iteration=iteration_number,
                temperature=temp,
                response_text=response_text,
                latency_seconds=latency,
            )
            candidates.append(candidate)
            logger.info(
                f"Candidate #{candidate_id_counter} generated by {model_name} in {latency}s"
            )
            candidate_id_counter += 1

    pool = CandidatePool(total_candidates=len(candidates), candidates=candidates)
    logger.info(
        f"Multi-Agent Candidate Pool Generation Complete. Total={len(candidates)}"
    )
    return pool